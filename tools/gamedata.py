#!/usr/bin/env python3
"""Render GAME_DATA.md from runtime-dumped tables.

Usage: gamedata.py [data_dir=data/baseline] [out=docs/GAME_DATA.md]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CAMPAIGNS = ["West", "Europe", "Britain", "Ireland", "Spain", "Italy", "East"]
CLASSES = {  # refName -> (region class, faction class)
    "West": ("class_21", "class_23"), "Europe": ("class_20", "class_29"),
    "Britain": ("class_28", "class_25"), "Ireland": ("class_17", "class_15"),
    "Spain": ("class_22", "class_18"), "Italy": ("class_16", "class_26"),
    "East": ("class_24", "class_27"),
}


def load(d, name):
    return json.loads((d / f"{name}.json").read_text(encoding="utf-8"))


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |")
    return "\n".join(out)


def num(v):
    return f"{v:g}" if isinstance(v, float) else str(v)


def rule_text(r):
    c = r.get("if")
    cond = ""
    if c:
        cond = (f"{c[0]}" if len(c) == 1 else
                f"has {' / '.join(c[2])}" if c[0] == "ability" else f"{c[0]} {c[1]} {c[2]}")
        cond = f"if {cond}: "
    parts = [f"{k} {'+' if v >= 0 else ''}{v}" for k, v in r.get("add", {}).items()]
    parts += [f"{k} = {v}" for k, v in r.get("set", {}).items()]
    return cond + ", ".join(parts)


def main(data_dir, out_file, rules_dir=None):
    d = Path(data_dir)
    rules = Path(rules_dir) if rules_dir else d
    units, techs, abil, camps = (load(d, n) for n in ("units", "techs", "abilities", "campaigns"))
    diff_all = load(rules, "difficulty")
    diff = diff_all["levels"]
    fx = load(rules, "tech_effects")
    tname = lambda i: techs[i]["selfName"] if 0 <= i < len(techs) else "—"
    md = []
    w = md.append

    w("# Swordfall: Kingdoms — Game Data Reference\n")
    w("> Generated by `tools/gamedata.py` from tables dumped **at runtime** out of the game "
      "(`tools/patch.py dump` / `check`), so every number is what the engine actually uses. "
      "Edit gameplay through `mods/data/*.json` and rebuild with `./patch.sh`.\n")
    w("Editable: **units** (`mods/data/units.json` → `class_3`), **techs** "
      "(`mods/data/techs.json` → `class_7`), **tech effects** (`mods/data/tech_effects.json` → "
      "`class_11.setTech`, `class_8.setTech`, `class_95.method_129`/`method_76`), **difficulty** "
      "(`mods/data/difficulty.json` → `class_95.method_34`/`method_109`), and **campaign reconstructions** "
      "(`mods/data/europe_1070.json` / `regional_campaigns.json` → campaign metadata, factions and regions). "
      "These are historically grounded strategy reconstructions; see "
      "[sources and limitations](MAP_RECONSTRUCTION.md) and [Grand Europe](EUROPE_1070.md). Abilities retain their original "
      "data. Changes vs the original game: `CHANGELOG.md`.\n")

    # ------------------------------------------------------------ campaigns
    w("## Campaigns (`class_9`)\n")
    rows = []
    for c in camps:
        ref = c["refName"]
        facs = load(d, f"factions.{ref}")
        regs = load(d, f"regions.{ref}")
        rows.append([c["selfIndex"], c["selfName"], f"`{ref}`", c["startDate"],
                     c["victoryPoints"], "yes" if c["isOpen"] else "no (locked)",
                     len(regs), len(facs) - 1, sum(r["baseGold"] for r in regs),
                     f"`{CLASSES[ref][0]}` / `{CLASSES[ref][1]}`"])
    w(table(["#", "Campaign", "ref", "Start", "VP to win", "Open", "Regions", "Factions",
             "Σ base gold", "Region / faction class"], rows))
    w("\n**Victory:** reach the campaign's VP target, then hold it for `vpCountdown` = **5** turns. "
      "VP = 1 per owned region + 2 per faction destroyed. While you are counting down, every AI "
      "faction applies the difficulty's `victoryGangUp` modifier against you.  \n"
      "**Defeat:** an AI faction completes its own VP countdown, or you own 0 regions.\n")
    w("The build unlocks recovered store campaigns only when their map assets are present "
      "and valid. The Open column above reflects the dumped build, including those unlocks.\n")

    # ------------------------------------------------------------ factions
    w("## Factions\n")
    w("Per faction: starting gold, starting regions (ownership is assigned from the faction's "
      "`regions` list at campaign start; the garrison comes from the region table), unique unit, "
      "starting general, and AI unit preferences (multipliers ≠ 1 on recruitment scoring).\n")
    for c in camps:
        ref = c["refName"]
        facs = load(d, f"factions.{ref}")
        regs = load(d, f"regions.{ref}")
        w(f"### {c['selfName']} (`{ref}`)\n")
        rows = []
        for f in facs[1:]:
            g = f.get("startGeneral") or {}
            gen = ""
            if g.get("selfName"):
                abil_s = ", ".join(f"{g[f'ability{i}']} {g[f'abilityLevel{i}']}"
                                   for i in (1, 2, 3) if g.get(f"ability{i}"))
                gen = f"{g['selfName']} (Lv{g['selfLevel']}; {abil_s})"
            start = [regs[i]["selfName"] for i in f["regions"] if i < len(regs)]
            army = {}
            for i in f["regions"]:
                for ui, n in enumerate(regs[i]["units"]):
                    if n:
                        army[units[ui]["selfName"]] = army.get(units[ui]["selfName"], 0) + n
            prefs = ", ".join(f"{units[i]['selfName']} ×{num(p)}"
                              for i, p in enumerate(f["unitPrefs"]) if p != 1)
            rows.append([f["selfName"], f["gold"], ", ".join(start),
                         sum(regs[i]["baseGold"] for i in f["regions"]),
                         ", ".join(f"{k} {v}" for k, v in army.items()),
                         f.get("uuName", ""), gen, prefs or "—"])
        w(table(["Faction", "Gold", "Start regions", "Income", "Start garrison",
                 "Unique unit", "Starting general", "AI unit prefs"], rows))
        w("")

    # ------------------------------------------------------------ units
    w("## Units (`class_3` → `class_11`, 38 entries)\n")
    w("Indices 0–2 are always recruitable and mercenaries need no tech; every other unit "
      "requires `hasTechs[unlockTech]`. `castle` = minimum region castle level. "
      "`commandCost` is derived (= morale) by the engine. Index 21 is the template every "
      "general is built from; slots 22–28 are empty but must stay (the engine iterates all 38).\n")
    rows = []
    for i, u in enumerate(units):
        if not u["selfName"]:
            rows.append([i, "*(unused slot)*"] + [""] * 18)
            continue
        bonus = []
        for k, label in (("cavBonus", "vsCav"), ("infBonus", "vsInf"), ("chargeBonus", "charge"),
                         ("chivBonus", "vsRoyal"), ("berserkLevel", "berserk"), ("armorBreak", "armorBreak")):
            if u.get(k):
                bonus.append(f"{label}+{u[k]}")
        if u.get("numChargeAttacks"):
            bonus.append(f"charges×{u['numChargeAttacks']}")
        flags = [f for f, k in (("AP", "hasArmorPiercing"), ("marksman", "hasMarksman"),
                                ("fast", "hasFastAttack"), ("devotion", "hasDevotion"),
                                ("elite", "isElite"), ("royal", "isRoyal")) if u.get(k)]
        abil_s = ", ".join(u[f"ability{n}"] + (f" {u[f'abilityLevel{n}']}" if u.get(f"abilityLevel{n}") else "")
                           for n in (1, 2, 3) if u.get(f"ability{n}"))
        rows.append([i, u["selfName"], u["selftype"], u["attackType"], u["attack"], u["hitPoints"],
                     u["armor"], u["meleeArmor"], u["rangedArmor"], u["speed"], u["range"],
                     u["morale"], u["recruitCost"], u["supplyCost"], u["upkeepCost"],
                     u["castleLevel"], "—" if i < 3 else f"{tname(u['unlockTech'])} ({u['unlockTech']})",
                     abil_s or "—", " ".join(bonus + flags) or "—", u["powerRating"]])
    w(table(["#", "Unit", "Type", "Attack type", "Atk", "HP", "Arm", "MArm", "RArm", "Spd",
             "Rng", "Mor", "Cost", "Supply", "Upkeep", "Castle", "Tech", "Abilities",
             "Bonuses / flags", "Power"], rows))

    # ------------------------------------------------------------ techs
    w("\n## Technologies (`class_7` → `class_32`, 29 entries)\n")
    w("`cost` is research gold; `costOriginal` is re-derived from it. Prereqs are tech indices.\n")
    w("Effects below are the **runtime** rules from `tech_effects.json` (compiled into the "
      "game, and checked against a live dump on every `./patch.sh`). The `attackBonus`/`hpBonus`/"
      "… fields in `techs.json` are not read by the engine.\n")
    econ = fx["economy"]
    rows = []
    for i, t in enumerate(techs):
        eff = [f"units: {rule_text(r)}" for r in fx["unit"] if r["tech"] == i]
        eff += [f"generals: {rule_text(r)}" for r in fx["general"] if r["tech"] == i]
        if str(i) in econ["income"]:
            eff.append(f"income ×{num(econ['income'][str(i)])}")
        if str(i) in econ["supply"]:
            eff.append(f"supply +{econ['supply'][str(i)]}")
        if i == econ["researchTech"]:
            eff.append("research costs ×0.75 (`techMenu.reduceTechCost`)")
        unl = [u["selfName"] for k, u in enumerate(units) if k >= 3 and u["selfName"]
               and u.get("unlockTech") == i and k != 21]
        if unl:
            eff.append("unlocks " + ", ".join(unl))
        pre = " + ".join(tname(t[k]) for k in ("prereq1", "prereq2") if t.get(k, -1) >= 0)
        rows.append([i, t["selfName"], t["cost"], pre or "—", "<br>".join(eff) or "—", t["dscr"]])
    w(table(["#", "Tech", "Cost", "Prereqs", "Runtime effect", "In-game text"], rows))

    # ------------------------------------------------------------ abilities
    w("\n## Abilities & general perks (`class_5` → `class_31`, 45 entries)\n")
    w("`start` is the level-1 value shown in the description; `cost` and `morale` are the raw "
      "`cost` / `moraleCost` fields. *General-pickable* is the `isUsedByGenerals` flag; perks "
      "like Royal Blood are granted to royal generals without being pickable.\n")
    rows = []
    for a in abil:
        val = f"{a['startValue']}{'%' if a['unitType'] == 'percent' else ''}"
        text = a["dscr"] + (val if a["hasLevels"] else "") + a["dscr2"]
        if a["drawbackValue"]:
            text += f"{a['drawbackValue']}{a['dscr3']}"
        rows.append([a["selfindex"], a["selfname"], "yes" if a["isUsedByGenerals"] else "—",
                     a["maximumLevel"] if a["hasLevels"] else "—", val, a["cost"], a["moraleCost"],
                     text.strip()])
    w(table(["#", "Ability", "General-pickable", "Max lvl", "Start", "Cost", "Morale", "Effect"], rows))

    # ------------------------------------------------------------ difficulty
    w("\n## Difficulty (`class_95.method_34`, catch-up in `method_109`) {#difficulty}\n")
    w(table(["Knob (`field`)", *diff.keys()],
            [[f"{k} (`{f}`)", *(num(diff[lv][k]) for lv in diff)] for k, f in (
                ("aiAttackCaution", "var_153"), ("playerThreatScale", "var_158"),
                ("aiIncomeMultiplier", "var_119"), ("victoryGangUp", "var_64"))]))
    w("""
- **aiAttackCaution** — multiplies the AI's attack-caution factor (`processAttackAI` param4). Lower ⇒ AI attacks with smaller odds.
- **playerThreatScale** — AI multiplies *your* region power by this when picking targets (lower ⇒ AI underestimates you and attacks you more), and divides your power by it when budgeting defence (lower ⇒ AI garrisons harder against you).
- **aiIncomeMultiplier** — AI gold per turn = `goldIncome × this` + catch-up bonus (below).
- **victoryGangUp** — during your VP countdown, each AI scales your power by this (×) and everybody else's by its inverse, so they pile onto you.
""")
    tiers = sorted(diff_all["catchUp"]["tiers"], key=lambda x: -x["minAiIncomeMultiplier"])
    w("**Catch-up bonus** (every AI, every turn): your income ÷ divisor of the first matching tier; "
      "none below the lowest.\n")
    w(table(["aiIncomeMultiplier ≥", "Divisor", "Levels"],
            [[num(x["minAiIncomeMultiplier"]), x["divisor"],
              ", ".join(lv for lv in diff if next((y for y in tiers if diff[lv]["aiIncomeMultiplier"] >= y["minAiIncomeMultiplier"]), None) is x) or "—"]
             for x in tiers]))
    w("")

    # ------------------------------------------------------------ formulas
    w("## Core formulas\n")
    w("""**Economy (per turn)** — `class_95` turn loop
- Player: `gold += goldIncome` (sum of owned regions' `totalGold`; region `totalGold` starts at `baseGold` and grows with `cityLevel`).
- AI: `gold += goldIncome × aiIncomeMultiplier + catchUpBonus` (`class_95.method_109`).
- Food cap = Σ region `totalFood`; recruiting needs gold **and** free supply (`supplyCost` per unit, shown as `35/44`).

**Melee hit** — `class_68.method_190`
```
dmg = attack (+ chargeBonus while numChargeAttacks > 0, decremented per hit)
    + cavBonus   if target is Cavalry   | + infBonus if target is Infantry
    + chivBonus  if target isRoyal
    - target.armor - target.meleeArmor   (skipped if hasArmorPiercing)
dmg = max(dmg, 1)
```
**Ranged hit** — `class_68.method_9` (projectile `class_66`)
```
hitChance = max(target.arrowAvoidBonus, 0.1) × (0.75 if point-blank: distance < shooter.selfsize)
dmg = power (×2 on a 25% roll if hasMarksman) + cav/inf/chiv bonus
    - target.armor - target.rangedArmor  (skipped if hasArmorPiercing),  min 1
```
**AI invasion choice** — `class_2.processAttackAI`
```
caution = f(gold: >10000→1.0, >6000→1.05, >4000→1.1, >2500→1.15, >1000→1.2, >600→1.25, >300→1.3, else 1.35)
        × aiAttackCaution × (1 + borderThreat/20)
targetPower × playerThreatScale if target is the player; ÷ clamp(strength,1.1,1.7) if it's the preferred enemy
targetPower × (1 + target.baseThreat/10)
ratio = ownPower / (targetPower × caution)     (neutral target)
      = ownPower / (targetPower × caution²)    (faction target)
attack the best-scoring neighbour if ratio > random(1.2 … 1.7)
```
""")

    w("""**Battle speed (v2.1)** — press **F** during a battle to cycle 1x → 2x → 3x by setting
`stage.frameRate` to 30/60/90 (`class_68.method_54`). Everything in the lane battle is
frame-driven, so it all scales together; the two real-time `Timer`s are scaled to match: the
enemy deployment planner (`class_154.var_419`, delay = 3000 / frameRate, kept in sync by
`class_68.method_3`) and Iron Will regeneration (`Unit.method_174`, counter advances
frameRate/30 per tick). The rate snaps back to 30 as soon as no battle is running.
""")

    # ------------------------------------------------------------ regions
    w("## Regions\n")
    for c in camps:
        ref = c["refName"]
        regs = load(d, f"regions.{ref}")
        facs = load(d, f"factions.{ref}")
        owner = {i: f["selfName"] for f in facs[1:] for i in f["regions"]}
        rows = []
        for i, r in enumerate(regs):
            gar = ", ".join(f"{units[ui]['selfName']} {n}" for ui, n in enumerate(r["units"]) if n)
            rows.append([i, r["selfName"], owner.get(i, facs[0]["selfName"]), r["baseGold"], r["baseFood"],
                         r["cityLevel"], r["farmLevel"], r["castleLevel"], r["baseThreat"],
                         gar or "—", ", ".join(r["connectionNames"])])
        w(f"<details><summary><b>{c['selfName']}</b> — {len(regs)} regions</summary>\n")
        w(table(["#", "Region", "Owner", "Gold", "Food", "City", "Farm", "Castle", "Threat",
                 "Garrison", "Connections"], rows))
        w("\n</details>\n")

    Path(out_file).write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {out_file}")


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[0] if a else ROOT / "data/baseline", a[1] if len(a) > 1 else ROOT / "docs/GAME_DATA.md",
         a[2] if len(a) > 2 else None)
